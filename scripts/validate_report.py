"""Structural validator. Visual review is reported separately, never inferred."""
import argparse,json,re
from pathlib import Path
from zipfile import ZipFile
from lxml import etree as E
from engine import NS,W,ROLES,BODY,HEADINGS
Q=lambda n:'{'+W+'}'+n
def val(e,path,attr='val',default=None):
 n=e.find(path,NS) if e is not None else None
 return n.get(Q(attr),'1' if attr=='val' and E.QName(n).localname in ['b','bCs','updateFields'] else default) if n is not None else default

def fields(root):
 stack=[];out=[];errors=[]
 for n in root.iter():
  if n.tag==Q('fldSimple'):out.append((n.get(Q('instr'),''),n))
  elif n.tag==Q('fldChar'):
   typ=n.get(Q('fldCharType'))
   if typ=='begin':stack.append({'code':'','node':n,'separated':False})
   elif typ=='separate':
    if not stack:errors.append('orphan field separator')
    else:stack[-1]['separated']=True
   elif typ=='end':
    if not stack:errors.append('orphan field end')
    else:
     f=stack.pop();out.append((f['code'],f['node']))
     if not f['separated']:errors.append('field has no result separator: '+f['code'])
  elif n.tag==Q('instrText'):
   if stack:stack[-1]['code']+=n.text or ''
   else:errors.append('instruction outside field')
 if stack:errors.append('unclosed field')
 return out,errors

def validate(path):
 errors=[];warnings=[];checks=0
 def check(ok,where,message):
  nonlocal checks
  checks+=1
  if not ok:errors.append({'location':where,'message':message})
 with ZipFile(path) as z:
  parts={n:E.fromstring(z.read(n),E.XMLParser(resolve_entities=False,no_network=True)) for n in z.namelist() if n.endswith('.xml')}
  doc=parts['word/document.xml'];styles=parts['word/styles.xml'];num=parts.get('word/numbering.xml');settings=parts['word/settings.xml']
  sm={s.get(Q('styleId')):s for s in styles.findall('w:style',NS)}
  names={sid:val(s,'w:name') for sid,s in sm.items()}
  names={sid:('Heading '+name[-1] if name in ['heading 1','heading 2','heading 3'] else name) for sid,name in names.items()};byname={name:sid for sid,name in names.items()}
  def style_chain(sid):
   result=[];seen=set()
   while sid in sm and sid not in seen:
    seen.add(sid);result.append(sm[sid]);sid=val(sm[sid],'w:basedOn')
   return result
  defaults=styles.find('w:docDefaults/w:rPrDefault/w:rPr',NS)
  def rprops(p,r=None):
   out=[]
   if r is not None:
    out.append(r.find('w:rPr',NS))
    cs=val(r,'w:rPr/w:rStyle')
    out.extend(s.find('w:rPr',NS) for s in style_chain(cs))
   sid=val(p,'w:pPr/w:pStyle',default=byname.get('Normal'))
   out.extend(s.find('w:rPr',NS) for s in style_chain(sid));out.append(defaults)
   return [x for x in out if x is not None]
  def prop(seq,path,attr='val'):
   for rp in seq:
    v=val(rp,path,attr)
    if v is not None:return v
   return None
  def pp_prop(p,path,attr='val'):
   v=val(p,'w:pPr/'+path,attr)
   if v is not None:return v
   for s in style_chain(val(p,'w:pPr/w:pStyle')):
    v=val(s,'w:pPr/'+path,attr)
    if v is not None:return v
  def number_level(p):
   nid=pp_prop(p,'w:numPr/w:numId');ilvl=pp_prop(p,'w:numPr/w:ilvl')
   if num is None or nid is None:return None
   n=num.find('w:num[@w:numId="'+nid+'"]',NS)
   aid=val(n,'w:abstractNumId')
   if aid is None:return None
   return num.find('w:abstractNum[@w:abstractNumId="'+aid+'"]/w:lvl[@w:ilvl="'+str(ilvl or 0)+'"]',NS)
  bookmarks={};bids={};ends={};allfields=[]
  for part,root in parts.items():
   if part=='word/document.xml' or part.startswith(('word/header','word/footer','word/footnotes','word/endnotes')):
    fs,fe=fields(root);allfields.extend(fs)
    for msg in fe:check(False,part,msg)
    for b in root.findall('.//w:bookmarkStart',NS):
     name=b.get(Q('name'));bid=b.get(Q('id'));check(name not in bookmarks,part,'duplicate bookmark name: '+str(name));check(bid not in bids,part,'duplicate bookmark id: '+str(bid));bookmarks[name]=b;bids[bid]=b
    for b in root.findall('.//w:bookmarkEnd',NS):ends[b.get(Q('id'))]=ends.get(b.get(Q('id')),0)+1
  for bid,b in bids.items():check(ends.get(bid)==1,'bookmark '+str(b.get(Q('name'))),'missing/duplicate bookmark end')
  for bid in ends:check(bid in bids,'bookmark id '+bid,'bookmark end without start')
  for code,node in allfields:
   m=re.match(r'\s*(REF|PAGEREF)\s+"?([^\s"\\]+)',code,re.I)
   if m:check(m[2] in bookmarks,'field '+code,'reference target missing')
  # Validate every paragraph role, including table cells; ignore field caches generated by Word TOC.
  for i,p in enumerate(doc.findall('.//w:p',NS),1):
   text=''.join(p.xpath('./w:r/w:t/text()',namespaces=NS));sid=val(p,'w:pPr/w:pStyle',default=byname.get('Normal'));name=names.get(sid,sid);where=f'word/document.xml paragraph {i} ({text[:32]})'
   if not text.strip() and not p.findall('.//w:instrText',NS):continue
   if name and name.lower().startswith('toc'):continue
   check(name in ROLES,where,'unclassified paragraph style; ordinary body must use 正文_改: '+str(name))
   if name not in ROLES:continue
   east,size,bold=ROLES[name]
   for r in [None]+p.findall('w:r',NS):
    if r is not None and not ''.join(r.xpath('./w:t/text()',namespaces=NS)):continue
    rp=rprops(p,r)
    check(prop(rp,'w:rFonts','eastAsia')==east,where,'Chinese font must be '+east)
    for key in ['ascii','hAnsi','cs']:check(prop(rp,'w:rFonts',key)=='Times New Roman',where,key+' font must be Times New Roman')
    check(prop(rp,'w:sz')==str(int(size*2)),where,'size must be '+str(size)+' pt')
    if name in HEADINGS+['参考文献标题','参考文献条目']:
     check((prop(rp,'w:b') not in [None,'0','false'])==bold,where,'incorrect bold weight')
   if name==BODY:
    check(pp_prop(p,'w:spacing','line')=='400' and pp_prop(p,'w:spacing','lineRule')=='exact',where,'body line spacing must be exactly 20 pt')
    check(pp_prop(p,'w:ind','firstLineChars')=='200',where,'body first-line indent must be 2 characters')
   if name in HEADINGS:
    level=HEADINGS.index(name);lv=number_level(p)
    check(lv is not None,where,'heading has no native numbering definition')
    check(pp_prop(p,'w:outlineLvl')==str(level),where,'heading outline level mismatch')
    check((pp_prop(p,'w:jc') or 'left')==('center' if level==0 else 'left'),where,'heading alignment mismatch')
    check(not re.match(r'^\s*\d+(?:\.\d+)*(?:\s|[、.])',text),where,'manual duplicate heading number')
    if lv is not None:
     check(val(lv,'w:pStyle')==sid,where,'numbering level must link heading style')
     check(val(lv,'w:numFmt')=='decimal',where,'heading numbering must be decimal')
     check(val(lv,'w:lvlText')=='.'.join('%'+str(k+1) for k in range(level+1)),where,'heading level pattern incorrect')
     for key in ['ascii','hAnsi','cs']:check(val(lv,'w:rPr/w:rFonts',key)=='Times New Roman',where,'heading NUMBER '+key+' font must be Times New Roman')
     check(val(lv,'w:rPr/w:b') not in [None,'0','false'],where,'heading NUMBER must be bold')
     check(val(lv,'w:rPr/w:sz')==str(int(size*2)),where,'heading NUMBER size mismatch')
   if name=='参考文献标题':check(number_level(p) is None,where,'reference heading must be unnumbered')
   codes=[c for c,n in fields(p)[0]]
   sequence={'图题':'Figure','表题':'Table','公式':'Equation','参考文献条目':'Reference'}.get(name)
   if sequence:
    check(any(re.match(r'\s*SEQ\s+'+sequence+r'\b',c) for c in codes),where,'missing native SEQ '+sequence+' field')
    if sequence!='Reference':
     check(any(re.match(r'\s*STYLEREF\s+1\s+\\s',c) for c in codes),where,'missing chapter STYLEREF field')
     check(any(re.search(r'\\s\s+1\b',c) for c in codes if re.match(r'\s*SEQ',c)),where,'SEQ must reset at chapter level 1')
    else:check(pp_prop(p,'w:ind','hanging') is not None,where,'reference requires hanging indent')
    check(bool(p.findall('w:bookmarkStart',NS)),where,'number requires bookmark')
   if name=='公式':check(bool(p.findall('m:oMath',NS)) or 'MathType' in text or bool(p.findall('.//w:object',NS)),where,'formula must be editable OMML or explicit MathType slot')
   if name==BODY:
    if not any(re.match(r'\s*REF\b',c) for c in codes):check(not re.search(r'\[\d+\]|[图表式]\s*[（(]?\d+[-.]\d+',text),where,'static numeric citation found; replace with REF field')
   check('错误!未找到引用源' not in text and 'Error! Reference source not found' not in text,where,'Word reports broken reference')
  # Check style and numbering even when a level is unused.
  for level,name in enumerate(HEADINGS):
   sid=byname.get(name);check(sid is not None,'styles','missing '+name)
   if sid:
    fake=E.Element(Q('p'));pp=E.SubElement(fake,Q('pPr'));E.SubElement(pp,Q('pStyle')).set(Q('val'),sid);lv=number_level(fake)
    check(lv is not None,'style '+name,'missing linked numbering')
    if lv is not None:
     check(val(lv,'w:rPr/w:rFonts','ascii')=='Times New Roman','style '+name,'heading NUMBER font incorrect')
     check(val(lv,'w:rPr/w:b') not in [None,'0','false'],'style '+name,'heading NUMBER not bold')
  for i,s in enumerate(doc.findall('.//w:sectPr',NS),1):
   check(val(s,'w:pgSz','w')=='11906' and val(s,'w:pgSz','h')=='16838','section '+str(i),'page must be source A4 dimensions')
   for edge in ['top','right','bottom','left']:check(val(s,'w:pgMar',edge)=='1701','section '+str(i),'margin '+edge+' must be 1701 twips')
  widths=[int(val(s,'w:pgSz','w'))-int(val(s,'w:pgMar','left'))-int(val(s,'w:pgMar','right')) for s in doc.findall('.//w:sectPr',NS)]
  maxw=min(widths,default=8504)
  for i,t in enumerate(doc.findall('.//w:tbl',NS),1):
   width=sum(int(c.get(Q('w'))) for c in t.findall('w:tblGrid/w:gridCol',NS));check(width<=maxw,'table '+str(i),'table grid exceeds page width')
   tw=val(t,'w:tblPr/w:tblW','w');typ=val(t,'w:tblPr/w:tblW','type')
   if typ=='dxa':check(int(tw)<=maxw,'table '+str(i),'explicit table width exceeds page')
  for i,e in enumerate(doc.findall('.//wp:extent',NS),1):check(int(e.get('cx'))<=maxw*635,'image '+str(i),'image exceeds page width')
  check(any(re.match(r'\s*TOC\b',c) for c,n in allfields),'document','missing automatic TOC')
  check(val(settings,'w:updateFields') in ['true','1'],'settings','updateFields must be enabled')
  check(any(re.match(r'\s*PAGE\b',c) for c,n in allfields),'footer','missing native page number')
  warnings.append('MANUAL: inspect all rendered pages for font fallback, formula layout, image aspect ratio, table splitting, caption adjacency and cover overflow.')
  warnings.append('MANUAL: after structural edits, Word must update fields and the entire TOC; structural PASS does not certify cached numbers.')
 return {'status':'FAIL' if errors else 'PASS','checks':checks,'errors':errors,'manual_checks':warnings}
def main():
 p=argparse.ArgumentParser();p.add_argument('input');p.add_argument('--json',dest='report');a=p.parse_args();r=validate(a.input)
 text=json.dumps(r,ensure_ascii=False,indent=2)
 if a.report:Path(a.report).write_text(text,encoding='utf-8')
 print(text);raise SystemExit(0 if r['status']=='PASS' else 1)
if __name__=='__main__':main()
